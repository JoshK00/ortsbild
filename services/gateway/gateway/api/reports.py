"""HTTP API used by the iOS app."""

from datetime import datetime
from typing import Annotated
from uuid import UUID

from fastapi import APIRouter, Depends, File, Form, HTTPException, Request, Response, UploadFile, status
from pydantic import BaseModel

from ..adapters import ios
from ..images import InvalidImageError
from ..ingest import EmptyReportError, IngestService
from ..schema import ReportStatus
from ..security import require_api_key

router = APIRouter(prefix="/v1/reports", tags=["reports"], dependencies=[Depends(require_api_key)])


class ReportReceipt(BaseModel):
    id: UUID
    status: ReportStatus
    received_at: datetime


class ReportStatusView(BaseModel):
    id: UUID
    status: ReportStatus
    updated_at: datetime


class ErrorDetail(BaseModel):
    code: str
    message: str


class ErrorResponse(BaseModel):
    detail: ErrorDetail


def _error(status_code: int, code: str, message: str) -> HTTPException:
    return HTTPException(status_code=status_code, detail={"code": code, "message": message})


@router.post(
    "",
    response_model=ReportReceipt,
    status_code=status.HTTP_201_CREATED,
    summary="Submit a new report from the app",
    description=(
        "Multipart form. `photo` or `text` (or both) is required. Sending the same `client_report_id` "
        "again returns the existing report with status code 200 instead of creating a duplicate, "
        "so the app can safely retry after a network error."
    ),
    responses={
        200: {"model": ReportReceipt, "description": "Report with this client_report_id already exists."},
        401: {"model": ErrorResponse},
        413: {"model": ErrorResponse},
        422: {"model": ErrorResponse},
    },
)
async def create_report(
    request: Request,
    response: Response,
    client_report_id: Annotated[UUID, Form(description="UUID generated by the app, used for safe retries.")],
    device_id: Annotated[str, Form(min_length=1, max_length=128, description="Anonymous, app-generated ID.")],
    created_at: Annotated[datetime, Form(description="When the citizen created the report (ISO 8601).")],
    lat: Annotated[float, Form(ge=-90, le=90)],
    lon: Annotated[float, Form(ge=-180, le=180)],
    accuracy_m: Annotated[float | None, Form(ge=0, description="Horizontal GPS accuracy in metres.")] = None,
    text: Annotated[str | None, Form(max_length=5000)] = None,
    anonymized_on_device: Annotated[
        bool, Form(description="True if faces and licence plates were blurred on the device.")
    ] = True,
    photo: Annotated[UploadFile | None, File(description="JPEG or PNG.")] = None,
) -> ReportReceipt:
    settings = request.app.state.settings
    ingest: IngestService = request.app.state.ingest

    if accuracy_m is not None and accuracy_m > settings.max_location_accuracy_m:
        raise _error(422, "location_too_imprecise", f"accuracy_m must be <= {settings.max_location_accuracy_m}")

    photo_bytes = None
    if photo is not None and photo.filename:
        photo_bytes = await photo.read(settings.max_photo_bytes + 1)
        if len(photo_bytes) > settings.max_photo_bytes:
            raise _error(413, "photo_too_large", f"photo must be <= {settings.max_photo_bytes} bytes")
        photo_bytes = photo_bytes or None

    if not photo_bytes and not (text and text.strip()):
        raise _error(422, "empty_report", "Send a photo, a text, or both.")

    incoming = ios.to_incoming(
        client_report_id=client_report_id,
        device_id=device_id,
        created_at=created_at,
        lat=lat,
        lon=lon,
        accuracy_m=accuracy_m,
        text=text,
        photo=photo_bytes,
        photo_content_type=photo.content_type if photo else None,
        anonymized_on_device=anonymized_on_device,
    )
    try:
        result = ingest.ingest(incoming)
    except InvalidImageError as exc:
        raise _error(422, "invalid_photo", str(exc)) from exc
    except EmptyReportError as exc:
        raise _error(422, "empty_report", str(exc)) from exc

    if not result.created:
        response.status_code = status.HTTP_200_OK
    report = result.report
    return ReportReceipt(id=report.id, status=report.status, received_at=report.received_at)


@router.get(
    "/{report_id}",
    response_model=ReportStatusView,
    summary="Current status of a report",
    description="The app maps `status` to a localized text itself.",
    responses={401: {"model": ErrorResponse}, 404: {"model": ErrorResponse}},
)
def get_report_status(report_id: UUID, request: Request) -> ReportStatusView:
    report = request.app.state.repo.get(report_id)
    if report is None:
        raise _error(404, "not_found", "No report with this id.")
    return ReportStatusView(id=report.id, status=report.status, updated_at=report.updated_at)
